import type { EvidenceRef } from "@/server/ai/schemas";
import type { SessionView, SourceView } from "./view-types";

/**
 * Markdown report with the 10 required sections:
 * 1 Objective · 2 Sources reviewed · 3 Key information · 4 Gaps · 5 Contradictions · 6 Outdated ·
 * 7 Unanswered questions · 8 Prioritised checklist · 9 Evidence & references · 10 Limitations & uncertainty.
 * Built only from the persisted session (no model call), so it never says more than the dashboard.
 */

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const day = (d: string | null | undefined) => (d ? d.slice(0, 10) : "—");
const quote = (q: string) => `> “${q.replace(/\s+/g, " ").trim()}”`;

export const FRESHNESS_REASON_TEXT: Record<string, string> = {
  dated_old: "Old stated date",
  references_past_cycle: "Refers to a past cycle",
  undated: "Undated (not necessarily outdated)",
  superseded_by_newer_source: "Possibly superseded by a newer source",
  expired_deadline: "Deadline has passed",
  old_version: "Marked as old / archived",
};

export const CATEGORY_TEXT: Record<string, string> = {
  fact: "Facts & figures",
  claim: "Other claims",
  date_deadline: "Dates & deadlines",
  requirement: "Requirements & eligibility",
  condition: "Conditions & rules",
  procedure: "Procedure",
  evidence: "Evidence & statistics",
};

export function sourceName(s: SourceView | undefined): string {
  if (!s) return "Unknown source";
  return s.title ?? s.url ?? s.fileName ?? s.alias;
}

export function renderMarkdownReport(v: SessionView): string {
  const src = new Map(v.sources.map((s) => [s.id, s]));
  const alias = (id: string) => src.get(id)?.alias ?? "S?";
  const refs = new Map<string, number>();
  const cite = (e: EvidenceRef) => {
    const k = `${e.sourceId}|${e.quote}`;
    if (!refs.has(k)) refs.set(k, refs.size + 1);
    return `[${alias(e.sourceId)}·E${refs.get(k)}]`;
  };
  const evidenceList: { n: number; e: EvidenceRef }[] = [];
  const evLine = (e: EvidenceRef) => {
    const before = refs.size;
    const c = cite(e);
    if (refs.size > before) evidenceList.push({ n: refs.size, e });
    return c;
  };

  const L: string[] = [];
  L.push(`# GapLens report: ${v.session.topic}`, "");
  L.push(`_Generated ${v.report ? day(v.report.generatedAt) : "(analysis not complete)"} · Session ${v.session.id}${v.report ? ` · Model: ${v.report.model}` : ""}_`, "");
  L.push("Labels: **Verified in source** = quote found verbatim in a reviewed source · **AI suggestion** = generated by the model, not stated in any source · **Requires verification** = confirm with an authoritative source.", "");

  // 1
  L.push("## 1. Research objective", "", `**Question:** ${v.session.question}`, "");
  if (v.session.objective) L.push(`**Objective:** ${v.session.objective}`, "");
  if (v.report?.coverageOverview) L.push(`**Coverage:** ${v.report.coverageOverview}`, "");

  // 2
  L.push("## 2. Sources reviewed", "", "| # | Source | Published / updated | Retrieved | Status |", "|---|---|---|---|---|");
  for (const s of v.sources) {
    const link = s.url ? (s.title ? `[${esc(s.title)}](${s.url})` : `<${s.url}>`) : esc(`${sourceName(s)} (uploaded PDF)`);
    const dates = s.publishedAt || s.modifiedAt ? `${day(s.publishedAt)}${s.modifiedAt ? ` / updated ${day(s.modifiedAt)}` : ""}` : "Undated";
    L.push(`| ${s.alias} | ${link}${s.official ? " (official domain)" : ""} | ${dates} | ${day(s.retrievedAt)} | ${s.status === "failed" ? `Failed: ${esc(s.error ?? "")}` : s.status} |`);
  }
  L.push("");

  // 3
  L.push("## 3. Key information found (verified in source)", "");
  if (v.claims.length === 0) L.push("_No verified claims were extracted._", "");
  const byCat = new Map<string, typeof v.claims>();
  for (const c of v.claims) byCat.set(c.category, [...(byCat.get(c.category) ?? []), c]);
  for (const [cat, list] of byCat) {
    L.push(`### ${CATEGORY_TEXT[cat] ?? cat}`, "");
    for (const c of list.slice(0, 40)) L.push(`- ${c.text} ${evLine({ claimId: c.id, sourceId: c.sourceId, quote: c.quote })}`);
    if (list.length > 40) L.push(`- …and ${list.length - 40} more in the dashboard.`);
    L.push("");
  }

  // 4
  L.push("## 4. Information gaps", "", "_“Not found in the reviewed sources” does not mean the information does not exist._", "");
  if (v.gaps.length === 0) L.push(v.coverage.length ? "_Every required topic was covered by at least one source._" : "_Gap detection has not run._", "");
  for (const g of v.gaps) {
    L.push(`### ${g.title} (${g.label === "not_found_in_sources" ? "Not found in reviewed sources" : "Potential gap"}, ${g.severity} priority)`, "");
    L.push(`- **Missing:** ${g.missingInformation}`);
    if (g.whyItMatters) L.push(`- **Why it matters:** ${g.whyItMatters}`);
    if (g.whatToInvestigate) L.push(`- **What to investigate (AI suggestion):** ${g.whatToInvestigate}`);
    if (g.evidence.length) L.push(`- **Related evidence:** ${g.evidence.map(evLine).join(" ")}`);
    L.push("");
  }

  // 5
  L.push("## 5. Possible contradictions", "", "_GapLens reports both sides and does not pick a winner._", "");
  if (v.contradictions.length === 0) L.push("_No contradictions were detected between the reviewed sources._", "");
  for (const c of v.contradictions) {
    L.push(`### ${c.kind === "cycle_mismatch" ? "Cycle mismatch: " : ""}${c.topic} (${c.severity})`, "", c.description, "");
    c.positions.forEach((p, i) => {
      L.push(`**Position ${i + 1}:** ${p.statement} ${p.evidence.map(evLine).join(" ")}`, "");
      for (const e of p.evidence.slice(0, 2)) L.push(quote(e.quote), `> (${alias(e.sourceId)}: ${esc(sourceName(src.get(e.sourceId)))})`, "");
    });
    if (c.possibleExplanations.length) L.push(`_Possible explanations (AI suggestion):_ ${c.possibleExplanations.join("; ")}`, "");
    if (c.authorityNote) L.push(`_Authority signals:_ ${c.authorityNote}`, "");
  }

  // 6
  L.push("## 6. Potentially outdated or undated information", "");
  if (v.freshness.length === 0) L.push("_No freshness warnings._", "");
  for (const f of v.freshness) {
    L.push(`- **${alias(f.sourceId)} · ${FRESHNESS_REASON_TEXT[f.reason] ?? f.reason}**${f.severity ? ` (${f.severity})` : ""}${f.origin === "ai" ? " _(AI-assisted)_" : ""}: ${f.description} ${f.evidence.map(evLine).join(" ")}`);
  }
  L.push("");

  // 7
  L.push("## 7. Unanswered questions (AI suggestions)", "");
  if (v.questions.length === 0) L.push("_None generated._", "");
  v.questions.forEach((q, i) => {
    L.push(`${i + 1}. **${q.question}**  `, `   ${q.whyItMatters}${q.suggestedSourceType ? ` _Where to look:_ ${q.suggestedSourceType}.` : ""}`);
  });
  L.push("");

  // 8
  L.push("## 8. Prioritised verification checklist", "");
  if (v.checklist.length === 0) L.push("_No checklist generated._", "");
  for (const p of ["high", "medium", "low"] as const) {
    const items = v.checklist.filter((c) => c.priority === p);
    if (!items.length) continue;
    L.push(`### ${p[0]!.toUpperCase()}${p.slice(1)} priority`, "");
    for (const c of items) L.push(`- [${c.done ? "x" : " "}] ${c.action}: _${c.rationale}_`);
    L.push("");
  }

  // 9
  L.push("## 9. Evidence & references", "");
  if (evidenceList.length === 0) L.push("_No evidence cited._", "");
  for (const { n, e } of evidenceList) {
    const s = src.get(e.sourceId);
    const name = sourceName(s);
    L.push(`**E${n}** · ${s?.alias ?? "S?"} · ${esc(name)}${s?.url && s.url !== name ? ` · ${s.url}` : ""}`, "", quote(e.quote), "");
  }

  // 10
  L.push("## 10. Limitations & uncertainty", "");
  const lim = v.report?.limitations?.length
    ? v.report.limitations
    : ["The analysis was not completed; sections above may be partial.", "“Not found in the reviewed sources” does not mean nonexistent; undated does not mean outdated."];
  for (const l of lim) L.push(`- ${l}`);
  L.push("");
  return L.join("\n");
}
